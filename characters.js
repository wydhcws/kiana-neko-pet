// 取角色设定；没有档案的角色给一份空白模板，由 prompt 让模型自己按认知扮演
function profile(name, game) {
  const g = GAMES[game] || GAMES[DEFAULT_GAME];
  const p = PROFILES[name] || {};
  return {
    name: name || '琪亚娜',
    game: game || DEFAULT_GAME,
    world: g.world,
    you: g.you,
    self: p.self || '我',
    tic: p.tic || '',
    traits: p.traits || '',
    friends: p.friends || '',
    motion: p.motion || null,   // 动作幅度等（没有就用默认，和琪亚娜一致）
    lines: p.lines || null,     // 专属固定台词（没有就用通用台词做用语替换）
    known: !!PROFILES[name],
  };
}

// 把为琪亚娜写的固定台词改成当前角色的口吻（AI 不可用时的兜底台词走这里）。
// 只替换三类专属用语：自称、对玩家的称呼、句尾口癖。
function adaptLine(text, p) {
  if (!text || (p.name === '琪亚娜' && p.you === '舰长')) return text;
  let s = text;
  if (p.you !== '舰长') s = s.split('舰长').join(p.you);
  if (p.self !== '本小姐') s = s.split('本小姐').join(p.self);
  if (p.tic !== '喵') {
    // 「喵」都出现在句尾或语气词之前，直接换掉/删掉不会破坏句子
    s = s.split('喵').join(p.tic);
    // 符号类口癖（♪）紧跟问号/句号时很别扭，去掉：「你呢♪？」→「你呢？」
    if (p.tic) s = s.split(p.tic + '？').join('？').split(p.tic + '。').join('。');
  }
  return s;
}

module.exports = { GAMES, PROFILES, profile, adaptLine, DEFAULT_GAME };
