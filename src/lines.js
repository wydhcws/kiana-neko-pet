export const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];

// L 可传入合并了角色专属台词的表；不传就是原来的 LINES
export function greetingFor(h, L = LINES) {
  if (h >= 5 && h < 11) return pick(L.greet.morning);
  if (h >= 11 && h < 14) return pick(L.greet.noon);
  if (h >= 14 && h < 18) return pick(L.greet.afternoon);
  if (h >= 18 && h < 23) return pick(L.greet.evening);
  return pick(L.greet.night);
}

// 启动问候：节日 > 星期（早上）> 时段
export function openingLine(d = new Date(), L = LINES) {
  const hol = HOLIDAYS[`${d.getMonth() + 1}-${d.getDate()}`];
  if (hol) return hol;
  const h = d.getHours();
  if (h >= 5 && h < 12 && Math.random() < 0.5) return L.weekday[d.getDay()];
  return greetingFor(h, L);
}

export function hourLine(h) {
  const extra = h === 12 ? '该吃午饭啦！' : h === 18 ? '下班时间到～' : h >= 23 || h < 5 ? '快去睡觉喵！' : h === 15 ? '下午茶时间！' : '继续加油喵！';
  return `现在是 ${h} 点整～${extra}`;
}

export function durationText(min) {
  const h = Math.floor(min / 60), m = min % 60;
  return h ? `${h} 小时${m >= 10 ? ` ${m} 分钟` : ''}` : `${m} 分钟`;
}
